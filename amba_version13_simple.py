"""Data Pre-Processing"""

big_mart_data.head()

big_mart_data['Item_Fat_Content'].value_counts()

big_mart_data.replace({'Item_Fat_Content': {'low fat':'Low Fat','LF':'Low Fat', 'reg':'Regular'}}, inplace=True)

big_mart_data['Item_Fat_Content'].value_counts()

"""Cleaning the Test data (same steps, using values from the training data)"""

test_data['Item_Weight'] = test_data['Item_Weight'].fillna(big_mart_data['Item_Weight'].mean())

miss_values_test = test_data['Outlet_Size'].isnull()
test_data.loc[miss_values_test, 'Outlet_Size'] = test_data.loc[miss_values_test, 'Outlet_Type'].apply(lambda x: mode_of_Outlet_size[x])

test_data.replace({'Item_Fat_Content': {'low fat':'Low Fat','LF':'Low Fat', 'reg':'Regular'}}, inplace=True)

"""Feature Engineering

Only 3 things are needed:
- Item_MRP (price)
- Outlet_Identifier (which store)
- Item_Identifier number (last 2 digits, e.g. FDA15 --> 15)
"""

# splitting features and target
X = big_mart_data.drop(columns='Item_Outlet_Sales', axis=1)
Y = big_mart_data['Item_Outlet_Sales']

# joining train and test features so both get exactly the same encoding
all_data = pd.concat([X, test_data], ignore_index=True)

# 1. Outlet (one column per store)
outlet = pd.get_dummies(all_data['Outlet_Identifier']).astype(float).values

# 2. Price effect for each outlet (outlet x log of MRP)
mrp = all_data['Item_MRP'].values
outlet_price = outlet * np.log(mrp)[:, None]

# 3. Item number as a smooth curve (spline)
item_number = all_data['Item_Identifier'].str[3:].astype(int).values.reshape(-1, 1)
item_curve = SplineTransformer(n_knots=16, degree=3).fit_transform(item_number)

# final feature matrix
features = np.hstack([outlet, outlet_price, item_curve])

# separating train rows and test rows
X_all = features[:len(X)]
X_final_test = features[len(X):]

"""Splitting the data into Training data & Testing Data"""

X_train, X_test, Y_train, Y_test = train_test_split(X_all, Y, test_size=0.2, random_state=2)

print(X_all.shape, X_train.shape, X_test.shape)

"""Machine Learning Model Training

Gamma Regressor (good for sales values, which are always positive)
"""

regressor = GammaRegressor(alpha=1e-4, max_iter=5000)

regressor.fit(X_train, Y_train)

"""Evaluation"""

# prediction on training data
training_data_prediction = regressor.predict(X_train)

# R squared Value
r2_train = metrics.r2_score(Y_train, training_data_prediction)

print('R Squared value = ', r2_train)

# prediction on test data
test_data_prediction = regressor.predict(X_test)

# R squared Value
r2_test = metrics.r2_score(Y_test, test_data_prediction)
print('R Squared value = ', r2_test)

# RMSE
rmse = np.sqrt(metrics.mean_squared_error(Y_test, test_data_prediction))
print('RMSE = ', rmse)

"""Final Predictions on Test.csv"""

# retraining on the full training data
regressor.fit(X_all, Y)

final_test_predictions = regressor.predict(X_final_test)

# creating the submission file
submission = pd.DataFrame({
    "Item_Identifier":   test_data["Item_Identifier"],
    "Outlet_Identifier": test_data["Outlet_Identifier"],
    "Item_Outlet_Sales": final_test_predictions,
})

# sales can't be lower than the minimum seen in training
submission["Item_Outlet_Sales"] = submission["Item_Outlet_Sales"].clip(lower=33)

submission.to_csv("submission.csv", index=False)
print(submission.head())
